const DICTS: Record<Locale, Dict> = { en, uk, fr, ru };

export const LOCALES: Array<{ id: Locale; name: string }> = [
  { id: "en", name: "English" },
  { id: "uk", name: "Українська" },
  { id: "fr", name: "Français" },
  { id: "ru", name: "Русский" },
];

export const isLocale = (v: string): v is Locale => v in DICTS;

export function t(locale: Locale, key: string): string {
  return DICTS[locale]?.[key] ?? DICTS.en[key] ?? key;
}

/** Мова з заголовка браузера, якщо людина ще нічого не обрала. */
export function localeFromHeader(header: string | null): Locale {
  if (!header) return "en";
  for (const part of header.split(",")) {
    const code = part.trim().slice(0, 2).toLowerCase();
    if (isLocale(code)) return code;
  }
  return "en";
}
