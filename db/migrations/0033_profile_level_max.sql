-- Стеля рівня окремим полем, а не словами в побажаннях.
--
-- Рівень уже читається з побажань, і після 0031 читається правильно. Але
-- вимагати від людини написати «No Senior, Lead, Head, Director or VP roles»
-- своїми словами — це перекладати на неї нашу роботу. Жива скарга 01.09
-- просила саме кнопку: «було б дуже зручно мати окремий фідбек типу "занадто
-- senior", бо "wrong role" не завжди точно передає проблему: сама сфера
-- вакансії може підходити, але саме рівень ні».
--
-- Кнопка мусить писати кудись, де немає розбору тексту. Поле — це:
--   1 junior / entry, 2 mid, 3 senior, 4 principal / staff / head / director.
-- Ті самі щаблі, що й levelTier у match.ts: два списки щаблів розійшлись би
-- першою ж правкою.
--
-- Порожнє поле нічого не робить, тож жоден наявний профіль не змінюється.
-- Значення означає СТЕЛЮ, а не рівень людини: «не вище за mid». Вакансія без
-- рівня в назві під стелю не підпадає ніколи — «не знаємо» і «не підходить»
-- тут різні речі, як і скрізь у підборі.
ALTER TABLE profiles ADD COLUMN level_max INTEGER;

