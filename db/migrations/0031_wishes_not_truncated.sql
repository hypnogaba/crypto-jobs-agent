-- Побажання, обрізані на 160-му символі, треба відновити.
--
-- `normalizeFreeText` різала КОЖНЕ поле до 160 символів. Для назви ролі це з
-- запасом, а побажання — абзац: у боті межа поля 1000 символів, на сайті 2000.
-- Тому все, що людина написала після 160-го символу, мовчки не доходило до
-- підбору.
--
-- Виміряно на живих даних 01.09: з одинадцяти профілів із побажаннями два
-- обрізані. У профілі 4231c8 з 595 написаних символів лишалось 160 — тобто
-- губилось 73%, разом із реченням «No Senior, Lead, Head, Director or VP
-- roles», через яке й прийшла скарга. У профілі f918f7 відрізало рівно
-- останнє речення «No Senior, Lead, Head or Director roles.»
--
-- Лікуємо не підстановкою, а забуттям. `wishes_en` ставимо в NULL, і підбір
-- одразу читає повний оригінал зі стовпця `wishes` (див. `wishesText`).
-- Разом із ним обнуляємо `normalized_from`: це відбиток тексту, з якого
-- зроблено переклад, і поки він збігається, `persistDerived` вважає роботу
-- зробленою й нового перекладу не замовляє. Тепер найближче збереження
-- профілю перекладе абзац наново, вже за новою межею.
--
-- Чому саме NULL, а не `wishes_en = wishes`: серед обрізаних можуть бути
-- рядки не латиницею, і копія кирилиці в стовпець «англійською» була б
-- неправдою. NULL чесно каже «перекладу ще немає».
UPDATE profiles
   SET wishes_en = NULL,
       normalized_from = NULL,
       updated_at = datetime('now')
 WHERE wishes_en IS NOT NULL
   AND wishes IS NOT NULL
   AND length(wishes_en) = 160
   AND length(wishes) > 160;

