-- Слід кожного дотику в боті.
--
-- Панель знала, скільки людей зареєструвалось, але не знала, чи вони взагалі
-- користуються ботом. Найближче до відповіді лежало в `webhook_updates` — та
-- таблиця бачить кожне оновлення, — але вона чиститься через добу
-- (`DELETE ... seen_at < -1 day`) і є захистом від повторів, а не історією.
-- Малювати графік по ній означало б показувати два дні й називати це
-- зростанням.
--
-- Тут навпаки: рядок лишається. Він дешевий — chat_id і рід дії, без тексту
-- повідомлення. Що людина написала, нас у цьому графіку не стосується, а
-- зберігати зайве означало б тримати листування без потреби.
CREATE TABLE IF NOT EXISTS bot_activity (
    id      INTEGER PRIMARY KEY AUTOINCREMENT,
    at      TEXT NOT NULL DEFAULT (datetime('now')),
    chat_id TEXT NOT NULL,
    -- message | button: натискання кнопки й написане повідомлення — різні
    -- речі, і різниця між ними каже, наскільки бот зрозумілий без клавіатури.
    kind    TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_bot_activity_at ON bot_activity(at);
