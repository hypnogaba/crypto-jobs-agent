-- Стан розмови в боті.
--
-- Досі онбординг у чаті був одним пострілом: «напиши одним реченням». На
-- «тест» бот відповів «Сфери: не визначено, Рівень: не визначено» і мовчки
-- прийняв порожній профіль — такий видавав би сміття щоранку.
--
-- Тепер це чотири питання кнопками, як на сайті. Питання зі станом потребує
-- пам'яті між повідомленнями: де ми зупинились і що вже обрано.
CREATE TABLE IF NOT EXISTS bot_state (
    chat_id    TEXT PRIMARY KEY,
    step       TEXT NOT NULL,               -- spheres | industries | seniority | where | salary
    draft      TEXT NOT NULL DEFAULT '{}',  -- JSON відповідей, що вже зібрані
    -- Клавіатуру редагуємо на місці, а не шлемо нову на кожен дотик:
    -- інакше чат перетворюється на стрічку з десяти однакових повідомлень.
    message_id INTEGER,
    updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
