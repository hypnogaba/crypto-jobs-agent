-- Вікно кандидатів читало на п'ять тисяч рядків більше, ніж потрібно.
--
-- EXPLAIN показував `SEARCH j USING INDEX idx_jobs_country (country=?)`:
-- SQLite брав індекс країни, витягав УСІ 35 895 глобальних вакансій і лише
-- потім відкидав старі за `fetched_at`. Потрібних серед них 27 944, тобто
-- майже вісім тисяч рядків читались намарно на КОЖНУ добірку.
--
-- Складений індекс дає шукати одразу «глобальні, свіжіші за дату».
-- Виміряно на живій базі тим самим запитом, що йде в добірку:
-- 39 332 → 31 381 прочитаних рядки (−20%), результат той самий, 634 рядки.
--
-- `country` першим, бо він рівність, а `fetched_at` діапазон: у складеному
-- індексі діапазон мусить стояти останнім, інакше решта стовпців не
-- використовується.
CREATE INDEX IF NOT EXISTS idx_jobs_country_fetched ON jobs_cache(country, fetched_at DESC);

-- Старий індекс лише на країну тепер зайвий: складений покриває і запити,
-- де країна єдина умова (префікс індексу). Зайвий індекс не безкоштовний —
-- скан пише в цю таблицю тисячі рядків за прогін, і кожен запис оновлює
-- КОЖЕН індекс.
DROP INDEX IF EXISTS idx_jobs_country;

