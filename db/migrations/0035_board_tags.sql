-- Дошка вміла оголосити країну й не вміла оголосити нішу.
--
-- Колекції Getro свій стовпець `tags` отримали (0022) і працюють ідеально:
-- у колекції Polychain 160 вакансій із 160 мають тег `web3`. Дошки такого
-- стовпця не отримали ніколи, тож `country_boards` могла сказати «це
-- Україна» і не могла сказати «це крипта».
--
-- Ціна цієї відсутності, виміряна на живому кеші 02.09:
--
--   board:global-jobstash          1651 вакансій, з тегом web3 — 36 (2%)
--   board:global-web3career         497 вакансій, з тегом web3 — 65 (13%)
--   board:global-cryptocurrencyjobs  69 вакансій, з тегом web3 —  9
--   board:global-remote3              7 вакансій, з тегом web3 —  1
--   ───────────────────────────────────────────────────────────────
--   разом                          2224 вакансії, невидимих     2113
--
-- Усі чотири дошки крипто-нішеві за визначенням: jobstash.xyz і web3.career
-- інших вакансій не тримають взагалі. Тег їм не ставився не через помилку в
-- правилі, а тому, що правило дивиться лише в назву вакансії й назву
-- компанії. «Senior Backend Engineer» у крипто-компанії слова «crypto» в
-- назві не має, і мати не мусить.
--
-- Читати опис не вихід: опис є лише в 21% рядків кеша (6672 з 32280).
-- Єдине надійне джерело ніші — саме джерело, і воно про себе знає.
--
-- Чому це важливо саме зараз: 16 профілів із 24 просили web3, а web3 це 3,6%
-- каталогу. Після цієї міграції та перетегування стане близько 10%, без
-- жодного нового джерела й без жодного зайвого запиту в мережу.
ALTER TABLE country_boards ADD COLUMN tags TEXT NOT NULL DEFAULT '[]';

-- Ніша ставиться лише там, де дошка нішева ЦІЛКОМ. `remotech`, `hireeing`,
-- `we-love-product` і всі DOU лишаються без тегу: серед них крипта
-- трапляється, але не становить їх, і чіпляти тег усьому вмісту було б тією
-- самою неправдою, тільки з іншого боку.
UPDATE country_boards
   SET tags = '["web3"]'
 WHERE name IN (
   'board:global-jobstash',
   'board:global-web3career',
   'board:global-cryptocurrencyjobs',
   'board:global-cryptocareers',
   'board:global-remote3'
 );

