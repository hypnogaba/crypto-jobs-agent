-- Ніша береться з колекції, а не з префікса джерела.
--
-- Правило в tags.ts вішало «web3» на КОЖНУ вакансію з Getro, бо Getro тримає
-- борди крипто-фондів. Але Getro тримає й будь-які інші: колекція 1200 —
-- ізраїльська дошка з Elbit, Teva, NVIDIA й Bank Leumi, і всі 412 її вакансій
-- лежали в кеші як web3. Разом таких рядків 761 із 1146.
--
-- Наслідок був не косметичний. Індустрія в підборі спирається саме на цей
-- тег, тож людина, яка обрала «Web3 і крипта», отримувала Teva Pharmaceuticals
-- із чесною позначкою «твоя індустрія».
--
-- Порожній список — правильна відповідь для колекції, про яку ми нічого не
-- знаємо: чотирнадцять числових знайдено переліком id, і вигадувати їм нішу
-- означало б повторити ту саму помилку, тільки дрібнішим шрифтом.
ALTER TABLE getro_collections ADD COLUMN tags TEXT NOT NULL DEFAULT '[]';

-- Шість, про які відомо, чиї вони: борди крипто-фондів і екосистем.
UPDATE getro_collections SET tags = '["web3"]'
 WHERE collection_id IN (858, 10223, 1118, 203, 1640, 390);
