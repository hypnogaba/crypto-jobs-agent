-- Один стовпець тримав відкритим текстом ключ від акаунта — і від двох дверей одразу.
--
-- `users.connect_token` обслуговував і вхід на сайт (`/enter?token=`, сесія на
-- 30 днів), і прив'язку Telegram (`t.me/…?start=`). Токен той самий, стовпець
-- той самий, строк 15 хвилин. Наслідків було три, і всі справжні:
--
--   1. Бот шле посилання входу ТЕКСТОМ у чат, тож токен читається з екрана і
--      зі скриншота. Двері прив'язки приймали його як свій — один дотик, і
--      чужий акаунт висів на Telegram того, хто скриншот побачив. Доставка йде
--      за users.telegram_chat_id, тож жертва мовчки переставала отримувати
--      добірки, а нападник отримував і їх, і всі наступні посилання входу.
--   2. Токен зі сторінки 03/03 (він же в t.me-посиланні) годився як токен
--      ВХОДУ: побачив посилання прив'язки — маєш чужий кабінет.
--   3. Хто отримав читання бази (дамп, зайвий SELECT в адмінці, підрядник),
--      мав не сліди, а придатні ключі від кожного акаунта, у якого в ту мить
--      висіло посилання.
--
-- Тепер у стовпці лежить SHA-256, і не від токена, а від пари
-- «призначення:токен»: sha256("link:"+t) для прив'язки, sha256("enter:"+t) для
-- входу. Розділення в самому дайджесті, а не в сусідньому стовпці, — навмисно:
-- окремий `purpose` був би другою умовою в WHERE, яку можна забути дописати, і
-- саме її колись і забули. Тут забути неможливо — токен іншого призначення не
-- знаходить рядка взагалі.
--
-- RENAME COLUMN, а не новий стовпець поруч. Дві причини:
--   • SQLite переносить разом зі стовпцем його UNIQUE і автоматичний індекс,
--     тож таблиця не перебудовується і жодного НОВОГО індексу не з'являється.
--     Правило 0044 (запис $1/млн проти читання $0.001/млн; обмежує нас запис)
--     лишається дотриманим — вартість видачі токена така сама, як була;
--   • жоден забутий `WHERE connect_token=?` не має мовчки шукати серед самих
--     NULL і виглядати як «посилання не працює». Хай падає видимо.
--
-- Живі токени переносимо? Ні, гасимо. Двічі неможливо: у D1 немає sha256()
-- (перехешувати в SQL нічим), а призначення старого рядка ніде не записане —
-- вгадувати, який із двох дайджестів рахувати, ми не станемо. Ціна для людини:
-- рядок «посилання застаріло» і одна команда /site або перезавантаження
-- сторінки підключення. Живих токенів у мить міграції не більше, ніж людей,
-- які за останні 15 хвилин натиснули /site, /admin або відкрили /telegram.
-- Виміряти перед застосуванням (у самій міграції числа не потрібні, але в
-- звіті про деплой — так):
--   npx wrangler d1 execute crypto-jobs-agent --remote --command "SELECT COUNT(*) all_rows, SUM(connect_token IS NOT NULL) with_token, SUM(connect_token IS NOT NULL AND connect_expires_at > datetime('now')) live FROM users"
--
-- ПОРЯДОК ДЕПЛОЮ: спершу ця міграція, потім Worker. Навпаки не можна — новий
-- код упаде на «no such column: connect_token_hash», і вебхук проковтне це у
-- своєму try/catch, тобто прив'язка мовчки перестане працювати. Сканер цих
-- стовпців не торкається взагалі (перевірено grep), його черга не має значення.
--
-- НАКОЧУЄТЬСЯ РІВНО ОДИН РАЗ. Другий прогін цього файлу впаде на першому ж
-- твердженні: `no such column: connect_token` (стовпця вже немає, він
-- перейменований у connect_token_hash). Ідемпотентним його не зробити: SQLite
-- не має ні RENAME COLUMN IF EXISTS, ні умовних тверджень поза тригером.
-- Знай це наперед, бо збій виглядає як зламана міграція, а насправді він і є
-- захистом: wrangler спиняється на першому твердженні, решта файлу не
-- виконується, тож ні живі хеші не гасяться вдруге, ні bot_state не чиститься
-- зайвий раз. Тому питаємо базу, а не пам'ять, ще ДО накату:
--   npx wrangler d1 execute crypto-jobs-agent --remote --command "SELECT name FROM schema_migrations ORDER BY name DESC LIMIT 3"
-- Якщо '0045_connect_token_hash.sql' там уже є, накочувати нема чого.
UPDATE users
   SET connect_token = NULL, connect_expires_at = NULL
 WHERE connect_token IS NOT NULL;

ALTER TABLE users RENAME COLUMN connect_token TO connect_token_hash;

-- Той самий відкритий токен лежав і тут: вебхук клав `link:<токен>` у крок і
-- лишав його там, доки людина не натисне «Так» (прибиральника bot_state немає
-- ні у web/, ні в scanner/). Тепер туди лягає хеш. Старі рядки новий код
-- прочитає як хеш і акаунта не знайде, тож людина побачила б «посилання
-- застаріло» замість підтвердження — прибираємо їх тут, а не лишаємо гнити.
DELETE FROM bot_state WHERE step LIKE 'link:%';

