-- Індекси в jobs_cache коштували вчетверо більше, ніж давали.
--
-- ЧОМУ ЦЕ ВЗАГАЛІ ВАЖЛИВО. Акаунт на платному тарифі (перевірено:
-- default_usage_model = standard, і за тиждень із днем на 114 млн читань
-- жодної помилки квоти). Ціни D1 різняться в ТИСЯЧУ разів:
--   читання — $0.001 за мільйон рядків
--   запис   — $1.00  за мільйон рядків
-- Тобто рахунок роблять записи, а не читання. Виміряно 04.09: 22 млн читань
-- ($0.66/міс) проти 254 тис. записів ($7.63/міс).
--
-- ЗВІДКИ ЗАПИСИ. `upsertJobs` у кожному прогоні переписує company, title,
-- location, remote, source, tags, posted_at, fetched_at, country, вилку й
-- опис — інакше кеш не оновлювався б. SQLite оновлює КОЖЕН індекс, що
-- містить хоч один зі змінюваних стовпців, незалежно від того, чи значення
-- справді інше. Виміряно погодинно: 26 374 запити на 110 875 записаних
-- рядків, тобто 4,2 запису на вакансію — один рядок і три індекси.
--
-- ПОРІГ ОКУПНОСТІ. Один такий індекс коштує 26 374 записи на добу, тобто
-- $0.79 на місяць. Щоб окупитись, він мусив би economити 1,3 мільйона
-- читань на добу. Виміряно, скільки економить кожен (запит вікна кандидатів
-- на живій базі):
--
--   idx_jobs_country_fetched   1 830 рядків на добірку  ≈ 37 тис./добу
--   idx_jobs_fetched          10 825 рядків на добірку  ≈ 245 тис./добу
--   idx_jobs_rank               −536 рядків, і ВДВІЧІ ПОВІЛЬНІШЕ
--
-- Жоден не дотягує й до п'ятої частини порога. `idx_jobs_rank` виявився
-- гіршим за відсутність: SQLite його брав і робив зайву роботу, 43,9 мс
-- проти 19,6 мс без нього.
--
-- ПІДСУМОК на живій базі: вікно кандидатів 29 443 -> 42 597 рядків
-- (+$0.008/міс) при 110 875 -> ~26 400 записів на прогін (-$2.52/міс), і
-- запит удвічі швидший.
--
-- ЩО ЛИШАЄТЬСЯ. `idx_jobs_dedupe(dedupe_key)` безкоштовний: dedupe_key не
-- входить у SET, тож скан його не чіпає. Автоіндекси первинного ключа й
-- унікального url — так само.
--
-- ПРАВИЛО НА МАЙБУТНЄ. Перш ніж додавати індекс у jobs_cache, спитати: чи
-- містить він стовпець, який переписує скан? Якщо так, він коштуватиме
-- $0.79 на місяць довічно, і мусить економити мільйони читань на добу, щоб
-- це виправдати. Індекс на стовпці, якого скан не чіпає, безкоштовний.
DROP INDEX IF EXISTS idx_jobs_country_fetched;
DROP INDEX IF EXISTS idx_jobs_fetched;
DROP INDEX IF EXISTS idx_jobs_rank;

