-- Акаунт народжується в мить, коли підключено Telegram, а не раніше.
--
-- Виміряно 02.09: із двадцяти чотирьох акаунтів сім не мають Telegram. На
-- них згенеровано 105 добірок і зроблено НУЛЬ подач на вакансію (проти 44
-- у сімнадцяти підключених). Двоє вже не мають жодної сесії, тобто до
-- власного кабінету не дістануться ніколи: вхід тут лише через бота, а бот
-- на незнайомий chat_id пропонує /start, тобто НОВИЙ акаунт.
--
-- Причина не в тому, що люди не хочуть Telegram, а в тому, що ми створювали
-- акаунт до того, як у нього зʼявився хоч один спосіб зв'язку. Кука на
-- тридцять днів була єдиним ключем, і разом із нею зникав профіль.
--
-- Тому анкета, заповнена на сайті, чекає тут, а не в `users`. Нічого не
-- горить: ні добірок, ні викликів моделі, ні рядка в статистиці. Людина, яка
-- не дійшла до бота, просто не залишає по собі сироти.
--
-- `id` лежить у куці, `token` іде в глибокому посиланні. Два різні значення
-- навмисно: куку читає лише наш домен, а токен людина носить у Telegram і
-- може переслати. Знання токена дає рівно одне право — забрати цю анкету
-- собі, і рівно один раз.
CREATE TABLE IF NOT EXISTS pending_signups (
    id              TEXT PRIMARY KEY,
    token           TEXT NOT NULL UNIQUE,
    locale          TEXT NOT NULL,
    timezone        TEXT NOT NULL,
    profile         TEXT NOT NULL,          -- JSON: те саме, що пише persistProfile
    raw_input       TEXT,                   -- текст або резюме, з якого розібрано
    source          TEXT NOT NULL DEFAULT 'freetext',
    -- Заповнює бот, коли акаунт уже створено. Сайт бачить це на наступному
    -- відкритті сторінки й перетворює куку на сесію: людина повертається в
    -- готовий кабінет, а не на форму входу.
    claimed_user_id TEXT,
    created_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_pending_created ON pending_signups(created_at);

-- Коли акаунт поставлено на паузу. `updated_at` для цього не годиться: його
-- рухає будь-яка правка профілю, а нам потрібен саме початок відліку.
ALTER TABLE users ADD COLUMN paused_at TEXT;

