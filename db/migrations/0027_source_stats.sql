-- Підсумки по джерелах, порахований раз на прогін.
--
-- Панель рахувала їх наживо: одинадцять запитів по jobs_cache за одне
-- відкриття, близько трьохсот тисяч прочитаних рядків. Сам лише блок «Джерела»
-- коштував 52 170 — бо групування за родом джерела читає таблицю цілком.
--
-- Доки таблиця була на дві тисячі рядків, це нікого не турбувало. Тепер їх
-- 26 тисяч, а безкоштовний D1 дає п'ять мільйонів читань на добу — і двадцять
-- відкриттів панелі з'їдають цей ліміт самі, ще до того, як хтось отримає
-- добірку. Ціна панелі має бути десятками рядків, а не сотнями тисяч.
--
-- Числа тут застарівають рівно на один прогін, і це прийнятно: питання панелі
-- «чи все добре з джерелами», а не «скільки вакансій цієї секунди».
CREATE TABLE IF NOT EXISTS source_stats (
    source     TEXT PRIMARY KEY,
    -- ats | aggregator | board | getro — щоб панель не розбирала префікси
    -- рядків знову.
    family     TEXT NOT NULL,
    jobs       INTEGER NOT NULL DEFAULT 0,
    fresh      INTEGER NOT NULL DEFAULT 0,   -- за останні три дні
    companies  INTEGER NOT NULL DEFAULT 0,
    updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_source_stats_family ON source_stats(family, jobs);
