-- Нік людини в Telegram.
--
-- В адмінці людина досі була вісьмома символами UUID: «06df703e». Це
-- ідентифікатор рядка, а не людина. Коли користувачів шестеро, власник читає
-- панель, щоб упізнати конкретну людину й написати їй, — а рядок «06df703e»
-- не дає зробити ні першого, ні другого.
--
-- Нік Telegram віддає в КОЖНОМУ оновленні (`message.from.username`), тож
-- зберігати його нічого не коштує: ми його весь час отримували й викидали.
-- Ніка може не бути взагалі — його вмикають у налаштуваннях, і мільйони
-- людей цього не робили, — тому поряд лежить ім'я, яке є завжди.
ALTER TABLE users ADD COLUMN telegram_username TEXT;
ALTER TABLE users ADD COLUMN telegram_name TEXT;

-- Журнал доданих посилань.
--
-- Джерело досі додавалося формою з трьох полів, і мовчки не додавалося,
-- якщо стрічка нічого не віддала: `addBoard` просто робив `return`, і в
-- адмінці не змінювалось нічого. Власник не міг відрізнити «додав» від
-- «нічого не сталось».
--
-- Тому кожна спроба лишає рядок — і вдала, і ні. Це не лише історія: це
-- єдине місце, де видно, ЧОМУ посилання не прийнялось.
CREATE TABLE IF NOT EXISTS source_intake (
    id       TEXT PRIMARY KEY,
    url      TEXT NOT NULL,
    at       TEXT NOT NULL DEFAULT (datetime('now')),
    -- added | duplicate | empty | unreachable | unknown
    verdict  TEXT NOT NULL,
    kind     TEXT,                        -- ats | board | feed
    target   TEXT,                        -- companies.slug або country_boards.name
    note     TEXT,                        -- людською мовою, що саме сталось
    found    INTEGER NOT NULL DEFAULT 0   -- скільки вакансій дала перевірка
);

CREATE INDEX IF NOT EXISTS idx_intake_at ON source_intake(at);

-- Глобальна стрічка серед національних дошок.
--
-- `country_boards.country` — NOT NULL, бо дошка країни без країни не має
-- сенсу. Але вставлене посилання не завжди національне: `remoteok.com` — це
-- та сама стрічка, тільки вакансії з неї потрібні всім. Досі такі стрічки
-- можна було додати лише правкою `aggregators.ts` і деплоєм сканера.
--
-- Зірочка означає «країни немає»: сканер перетворює її на NULL у вакансії, а
-- NULL у `jobs_cache.country` — це рівно «видно всім» (див. digest.ts, умова
-- `j.country IS NULL OR j.country = ?`). Окремої колонки не заводимо: значень
-- у цьому полі й так рівно два види, і зайвий прапорець довелося б тримати
-- узгодженим із країною вручну. Схему це не змінює — лише домовленість,
-- яку читають boards.ts і адмінка.
