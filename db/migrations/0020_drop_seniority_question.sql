-- Питання про рівень прибрано з анкети.
--
-- Чому. Бал за рівень спирався на тег, який сканер брав із НАЗВИ вакансії,
-- а тегу не мали 14 049 рядків із 22 674 — на 62% кеша відповідь людини не
-- робила нічого. Тега `middle` не існувало взагалі, хоч кнопка на сайті
-- була: така людина не могла отримати збіг у принципі й лише платила штраф
-- (−2 за senior, −4 за lead) на 7 867 вакансіях. За весь час жодна скарга
-- не назвала рівень причиною, і всі seniority_weight лишились одиницями.
--
-- Стовпці НЕ видаляємо. D1 переживає ALTER TABLE DROP COLUMN погано, а
-- користі з видалення тут нуль: код їх більше не читає й не пише, тож вони
-- просто лежать. Зате при потребі видно, що саме люди були відповіли.

-- Свій рівень словами людини («head of BD», «founder») переїжджає в
-- побажання — там такі слова справді шукаються, у назві вакансії й в описі.
-- Сьогодні таких рядків нуль, але міграція має бути правдою й завтра: між
-- цим коментарем і деплоєм хтось може встигнути заповнити поле.
UPDATE profiles
   SET wishes = TRIM(COALESCE(wishes || ' · ', '') || custom_seniority),
       updated_at = datetime('now')
 WHERE custom_seniority IS NOT NULL
   AND TRIM(custom_seniority) <> ''
   AND (wishes IS NULL OR wishes NOT LIKE '%' || custom_seniority || '%');

-- Вага, вивчена зі скарг на рівень, більше нікуди не входить. Повертаємо її
-- в одиницю, щоб рядок не виглядав так, ніби система досі щось нею робить.
UPDATE user_tuning SET seniority_weight = 1.0 WHERE seniority_weight <> 1.0;
