-- Слід від правок профілю, зроблених не руками людини.
--
-- Кнопка «Інше — напишу словами» досі писала текст у `feedback.note`, і його
-- не читав НІХТО: ані код, ані запит, ані панель. Бот при цьому відповідав
-- «Дякую, врахую. Завтрашня добірка буде точнішою» — тобто рівно ту неправду,
-- за яку ми вже одного разу переписували міграцію 0009.
--
-- Тепер написане розбирається в конкретні поля профілю. А щойно щось міняє
-- профіль людини без її прямого дотику, потрібні дві речі, яких досі не було:
--
--   1. скасування. Модель помиляється, і людина мусить мати кнопку «ні, не
--      це» — інакше вона платить за нашу помилку своєю добіркою;
--   2. слід. Коли профіль поїде, питання «хто це зробив» мусить мати
--      відповідь, а не здогад. `before`/`after` — це JSON лише тих полів,
--      яких торкнулись.
--
-- Таблиця свідомо проста: ні версій, ні гілок. Скасувати можна останню
-- незакриту правку, і цього досить — людина скасовує те, що щойно побачила
-- на екрані, а не подію тижневої давності.
CREATE TABLE IF NOT EXISTS profile_edits (
  id         TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- Звідки прийшла правка: `note` — розбір коментаря під добіркою.
  source     TEXT NOT NULL,
  -- Слова людини, з яких зроблено правку. Без них слід нічого не пояснює.
  said       TEXT,
  before_json TEXT NOT NULL,
  after_json  TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  undone_at  TEXT
);

CREATE INDEX IF NOT EXISTS idx_profile_edits_user
    ON profile_edits (user_id, created_at DESC);

