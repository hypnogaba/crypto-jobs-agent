-- Зарплата в профілі — завжди РІЧНА в базі, місячна на екрані.
--
-- У полі стояло просто «Зарплата від», без періоду. Люди пишуть туди місячну —
-- так думають і в Європі, і в Україні, — а вакансії зведені до річних. Тобто
-- «3000» означало «3000 на рік», суму, якої не буває, і людина мовчки не
-- проходила за жодною вакансією.
--
-- Гірше було в розборі вільного тексту: він відкидав усе менше за 20 000 як
-- помилку. «Шукаю фронтенд, 3000 євро» давало профіль ЗОВСІМ без зарплати —
-- людина бачила порожнє поле там, де щойно назвала суму.
--
-- Рішення просте, бо продукт уже його прийняв: поле МІСЯЧНЕ й так і
-- підписане. У базі лежить річна — одна одиниця виміру на всю систему, — а
-- людині показуємо її ж місячне число.
--
-- Наявні два рядки: 3000 (місячна, з форми) і 36000 (уже річна). Множимо лише
-- те, що явно місячне: річної зарплати нижче двадцяти тисяч у наших вакансіях
-- не буває, а місячна вища за двадцять тисяч тут ще не траплялась. Умова
-- звужена за величиною, тож повторний запуск нічого не подвоїть.
UPDATE profiles SET salary_min = salary_min * 12
 WHERE salary_min IS NOT NULL AND salary_min > 0 AND salary_min < 20000;
