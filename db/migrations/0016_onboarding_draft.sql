-- Чернетка анкети між кроком 1 і кроком 2.
--
-- Досі вона їхала в куці nr_draft. Next серіалізує значення куки через
-- encodeURIComponent, а українська літера в UTF-8 — це два байти, тобто шість
-- символів (%D0%BF). Виміряно: 444 українські символи дають 2 723 байти, тоді
-- як 2 500 англійських — 3 433. Стеля браузера — 4 096 байтів, і він ріже куку
-- МОВЧКИ. Тож DRAFT_TEXT_MAX = 2 500, підібраний під латиницю, для кирилиці
-- означав реальну межу близько 660 символів.
--
-- Наслідок був не «текст обрізався», а гірший: кука не зберігалась зовсім,
-- readDraft() віддавав null, і /onboarding показував залогіненій людині СТАРИЙ
-- рядок із profiles замість щойно розібраного тексту. Людина писала про себе
-- тези — і бачила чужі їй галочки, без жодного натяку, що її текст загубився.
--
-- У базі місця вистачає і на текст, і на підстави («бо ти написав …»), яких у
-- куку вже не влізло б у жодній мові.
CREATE TABLE IF NOT EXISTS onboarding_drafts (
    id         TEXT PRIMARY KEY,
    text       TEXT NOT NULL,
    parsed     TEXT NOT NULL,          -- JSON: ParsedProfile разом з evidence і leftover
    created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Чужий текст не має лежати вічно. Рядок видаляється, щойно анкету збережено;
-- індекс потрібен прибиральнику, який зносить покинуті чернетки старші за добу.
CREATE INDEX IF NOT EXISTS idx_drafts_created ON onboarding_drafts(created_at);
