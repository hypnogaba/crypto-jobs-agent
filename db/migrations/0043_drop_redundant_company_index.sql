-- Нас обмежує ЗАПИС, а не читання, і один індекс тут був зайвий.
--
-- Виміряно 04.09: скан за одну годину зробив 110 875 записів при
-- безкоштовній стелі 100 000 на добу. Читань за той самий день 2,7 млн зі
-- стелі 5 млн, тобто запас удвічі. Отже вузьке місце — запис.
--
-- Звідки стільки. `upsertJobs` оновлює `fetched_at` у КОЖНОЇ побаченої
-- вакансії щоскану — інакше правило свіжості не працює. Оновлення одного
-- рядка тягне за собою оновлення кожного індексу, де це поле є, тож на ~26
-- тисяч вакансій виходить ~110 тисяч записів: приблизно чотири на рядок.
--
-- `idx_jobs_company(company_key)` — префікс `idx_jobs_rank(company_key,
-- posted_at DESC, fetched_at DESC)`, тобто цілком ним покривається.
-- Перевірено на живій базі: після зняття EXPLAIN дає
-- `SEARCH jobs_cache USING INDEX idx_jobs_rank (company_key=?)`, а вікно
-- кандидатів читає стільки ж. Запитів лише по company_key у коді немає
-- жодного.
--
-- Це прибирає близько 26 тисяч записів на добу, тобто чверть усього
-- бюджету, і не коштує жодного зайвого читання.
--
-- На майбутнє, коли з'явиться спокуса додати індекс у jobs_cache: записи
-- ростуть із РОЗМІРОМ КЕША, читання — з КІЛЬКІСТЮ ЛЮДЕЙ. Індекс, що
-- економить читання, окупається зі зростанням аудиторії; зайвий індекс
-- коштує щодня і не окупається ніколи.
DROP INDEX IF EXISTS idx_jobs_company;

