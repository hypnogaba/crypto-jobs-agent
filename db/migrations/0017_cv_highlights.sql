-- cv_highlights — те з резюме, чого не ловить жодна кнопка: стек, роки,
-- мови, ринки. Досі текст CV розбирали один раз на галочки й забували:
-- стовпець cv_text ніхто не читав, а підбір не знав про людину нічого,
-- крім одинадцяти сфер. Тепер короткий витяг лежить окремо, людина його
-- бачить і може правити, а переранжування отримує його в промпті.
ALTER TABLE profiles ADD COLUMN cv_highlights TEXT;

-- Звідки взявся текст чернетки. Досі persistProfile вгадував це за довжиною
-- (`> 800 символів = резюме`), тож тези на тисячу символів лягали в базу як
-- mode='cv' з порожнім raw_input: на профілі це неправда, і людина потім не
-- розуміла, чому «її текст» зник. Тепер сторінка, яка приймає файл, каже це
-- прямо.
ALTER TABLE onboarding_drafts ADD COLUMN source TEXT NOT NULL DEFAULT 'freetext';
