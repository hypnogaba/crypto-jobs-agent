-- Рахувати при скані, а не при кожному погляді.
--
-- Виміряно 02.09 на живій базі: одне відкриття головної коштує 236 тисяч
-- прочитаних рядків D1 (74 612 на три числа під заголовком і 161 379 на
-- стрічку з десяти вакансій). Сторінка добірок коштувала 1.8 мільйона, доки
-- її не полагодили того ж дня.
--
-- За добу база показала 38 мільйонів прочитаних рядків при сімнадцяти живих
-- людях. Дві третини з них це головна: приблизно сотня відкриттів на день,
-- кожне по чверть мільйона. Добірки всіх сімнадцяти людей на цьому тлі це
-- 2%. Тобто навантаження створюють не користувачі, а відвідувачі, і воно
-- росте від трафіку, якого ми ще навіть не шукали.
--
-- Причина проста: це агрегати по всій таблиці, а дані під ними змінюються
-- ДВІЧІ НА ДОБУ, коли працює скан. Ми перераховували на кожен запит те, що
-- змінюється двічі на день.
--
-- Тому таблиця. Сканер наповнює її наприкінці прогону, сторінка читає
-- кілька рядків за первинним ключем. Це не новий прийом у проєкті:
-- `source_stats` для панелі працює саме так.
--
-- Порожня таблиця означає «скан ще не відпрацював», і сторінка тоді просто
-- не показує чисел. Запасного шляху з живими запитами тут навмисно немає:
-- він був би другою копією тих самих SQL у другому пакеті, і саме такі
-- копії розходяться першою ж правкою.
CREATE TABLE IF NOT EXISTS site_stats (
    key        TEXT PRIMARY KEY,
    value      TEXT NOT NULL,          -- число рядком або JSON
    updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

