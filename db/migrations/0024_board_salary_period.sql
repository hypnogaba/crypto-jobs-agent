-- Період зарплати на дошці.
--
-- `parseSalary` кладе суму з заголовка як є, а дошки називають різні періоди.
-- Перевірено на живих даних: DOU дає 350–4500 (це місяць), GermanTechJobs —
-- 12 000–163 000 (це рік). Обидві суми лежали в одній колонці, тож київська
-- вакансія на $3000/міс не проходила фільтр людини, яка просить $60k на рік,
-- і водночас виглядала в кабінеті жалюгідно поруч із річними.
--
-- Це властивість ДОШКИ, а не здогад по числу. Вгадувати за величиною спокусливо
-- («$700 на рік не буває»), але тоді справжня річна зарплата в бідній країні
-- перетворилась би на вигадану — а помилка тут коштує людині показаної або
-- прихованої вакансії.
--
-- Значення за замовчуванням «year» означає «нічого не змінюється»: усі, крім
-- DOU, поводяться точно як раніше, поки хтось не перевірить їхню дошку й не
-- напише інше.
ALTER TABLE country_boards ADD COLUMN salary_period TEXT NOT NULL DEFAULT 'year';

UPDATE country_boards SET salary_period = 'month' WHERE name LIKE 'board:dou%';

-- Уже збережене теж треба виправити: 62 вакансії DOU лежать у кеші місячними
-- сумами. Помножити можна рівно один раз, тому умова звужена і за джерелом,
-- і за величиною — повторний прогін цієї міграції нічого не подвоїть.
UPDATE jobs_cache
   SET salary_min = salary_min * 12,
       salary_max = CASE WHEN salary_max IS NOT NULL THEN salary_max * 12 END
 WHERE source LIKE 'board:dou%'
   AND salary_min IS NOT NULL
   AND salary_min < 12000;
