import { describe, expect, it } from "vitest";
import { planPrune, chunk } from "./prune.js";

/**
 * Головне правило прибирання: вакансію, яку комусь надсилали, не видаляємо
 * ніколи. У схемі стоїть `sent.job_id ... ON DELETE CASCADE`, тож видалення
 * рядка кеша забрало б і рядок `sent`, а він тримає дві незамінні речі —
 * захист від повтору й історію кабінету.
 *
 * Найгірший наслідок не «зникла історія», а тихий: id вакансії виводиться з
 * її адреси, тож видалена сьогодні й побачена завтра вакансія отримає той
 * самий id — і піде людині вдруге, хоч вона вже могла податись.
 */
describe("що саме прибирати", () => {
  it("надіслане не видаляється, скільки б йому не було років", () => {
    const stale = ["a", "b", "c", "d"];
    const sent = new Set(["b", "d"]);
    expect(planPrune(stale, sent)).toEqual({ drop: ["a", "c"], kept: 2 });
  });

  it("нічого не надсилали — прибирається все старе", () => {
    expect(planPrune(["a", "b"], new Set())).toEqual({ drop: ["a", "b"], kept: 0 });
  });

  it("усе старе надсилали — не видаляємо нічого", () => {
    expect(planPrune(["a", "b"], new Set(["a", "b"]))).toEqual({ drop: [], kept: 2 });
  });

  it("порожній вхід не ламає план", () => {
    expect(planPrune([], new Set(["a"]))).toEqual({ drop: [], kept: 0 });
  });
});

describe("пакети", () => {
  it("ділить так, щоб один DELETE не отримав тисячі параметрів", () => {
    expect(chunk([1, 2, 3, 4, 5], 2)).toEqual([[1, 2], [3, 4], [5]]);
  });

  it("коротший за пакет список лишається одним пакетом", () => {
    expect(chunk([1, 2], 500)).toEqual([[1, 2]]);
  });

  it("порожній список не дає порожнього пакета", () => {
    expect(chunk([], 500)).toEqual([]);
  });
});
